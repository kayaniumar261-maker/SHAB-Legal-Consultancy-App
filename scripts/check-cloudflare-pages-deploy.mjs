import assert from 'node:assert/strict';
import fs from 'node:fs';
import yaml from 'js-yaml';
import {validateProject,entryAsset} from './cloudflare-pages-deploy.mjs';
const valid={success:true,result:{name:'shab-legal-consultancy-app',subdomain:'shab-legal-consultancy-app.pages.dev',production_branch:'production-existing'}};
assert.equal(validateProject(valid),'production-existing');
assert.throws(()=>validateProject({...valid,success:false}));
assert.throws(()=>validateProject({...valid,result:{...valid.result,subdomain:'another-site.pages.dev'}}));
assert.throws(()=>validateProject({...valid,result:{...valid.result,production_branch:'main\nbranch=evil'}}));
assert.equal(entryAsset('<script type="module" crossorigin src="/assets/index-123.js"></script>'),'/assets/index-123.js');
assert.throws(()=>entryAsset('<html>Login page</html>'));
assert.throws(()=>entryAsset('<script src="/assets/../index.js"></script>'));
const workflow=yaml.load(fs.readFileSync('.github/workflows/app-quality.yml','utf8'));
assert.deepEqual(workflow.jobs['deploy-pages'].needs,['verify','package-web']);
assert.match(workflow.jobs['deploy-pages'].if,/refs\/heads\/shab-2.0/);
const deploy=workflow.jobs['deploy-pages'].steps.find(s=>s.name==='Deploy existing Pages project');
assert.match(deploy['working-directory'],/runner.temp/);
assert.match(deploy.run,/wrangler@4\.148\.0 pages deploy site/);
assert.doesNotMatch(deploy.run,/wrangler preview/);
assert.match(deploy.if,/configured/);
console.log('Cloudflare Pages deployment checks passed: existing-site/branch validation, artifact dependency, isolated Pages deployment, credential guard and live entry verification.');
